// Renders tokens as a Tailwind CSS v4 theme. Tailwind utilities read these
// variables at runtime, so the mobile block makes the type scale responsive
// without any extra classes.

const ROLE_VARIABLES = {
  background: 'background',
  surface: 'surface',
  inverse: 'inverse',
  foreground: 'foreground',
  muted: 'muted',
  primary: 'primary',
  primaryForeground: 'primary-foreground',
  border: 'border',
};

const MOBILE_BREAKPOINT = 639; // just below Tailwind's sm breakpoint

const rem = (pixels) => `${Math.round((pixels / 16) * 10000) / 10000}rem`;

export function buildThemeCss(tokens) {
  const lines = [];
  const mobile = [];
  const { colors, fonts, type, spacing, radii, shadows, container } = tokens;

  lines.push(`/* Generated by Siteshift from ${tokens.source ?? 'a capture'} */`);
  lines.push('@theme {');

  lines.push('  /* Colors */');
  for (const [role, variable] of Object.entries(ROLE_VARIABLES)) {
    const value = colors.roles[role];
    if (value) lines.push(`  --color-${variable}: ${value};`);
  }
  const roleHexes = new Set(Object.values(colors.roles).filter(Boolean));
  colors.palette
    .filter((entry) => !roleHexes.has(entry.hex))
    .forEach((entry, i) => lines.push(`  --color-palette-${i + 1}: ${entry.hex};`));

  if (fonts.body || fonts.heading) {
    lines.push('', '  /* Fonts */');
    if (fonts.body) {
      lines.push(`  --font-sans: ${fonts.body.stack};`);
      lines.push(`  --font-body: ${fonts.body.stack};`);
    }
    if (fonts.heading) lines.push(`  --font-heading: ${fonts.heading.stack};`);
  }

  if (type.scale.length) {
    lines.push('', '  /* Type scale (desktop sizes; mobile overrides below) */');
    for (const step of type.scale) {
      lines.push(`  --text-${step.name}: ${rem(step.size)};`);
      if (step.lineHeight) lines.push(`  --text-${step.name}--line-height: ${step.lineHeight};`);
      if (step.letterSpacing) lines.push(`  --text-${step.name}--letter-spacing: ${step.letterSpacing};`);
      if (step.mobile !== step.size) mobile.push(`    --text-${step.name}: ${rem(step.mobile)};`);
    }
  }

  if (spacing.base && spacing.base % 4 !== 0) {
    lines.push('', `  /* Spacing unit: the site uses a ${spacing.base}px grid */`);
    lines.push(`  --spacing: ${rem(spacing.base)};`);
  } else if (spacing.base) {
    lines.push('', `  /* Spacing: the site uses a ${spacing.base}px grid, which fits Tailwind's default 4px unit */`);
  }

  if (radii.values.length) {
    lines.push('', '  /* Radii */');
    for (const r of radii.values) lines.push(`  --radius-${r.name}: ${r.value}px;`);
  }

  if (shadows.length) {
    lines.push('', '  /* Shadows */');
    for (const s of shadows) lines.push(`  --shadow-${s.name}: ${s.value};`);
  }

  if (container.width) {
    lines.push('', '  /* Content width, use as max-w-site */');
    lines.push(`  --container-site: ${rem(container.width)};`);
  }

  lines.push('}');

  if (mobile.length) {
    lines.push('', `@media (max-width: ${MOBILE_BREAKPOINT}px) {`, '  :root {', ...mobile, '  }', '}');
  }

  return `${lines.join('\n')}\n`;
}
